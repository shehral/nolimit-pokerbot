"""Bundle the bot into ONE self-contained file: bot/dist/nolimit_bot.py (for a submission that takes a single file).

How: the sources of bot_tables.py, brain.py and adapter.py are embedded as string literals and executed into module
objects registered under the same unique names the bot's own loaders look up first (nolimit_bot_tables,
nolimit_bot_brain, nolimit_bot_adapter); then shell.py's code runs in the bundle's own namespace, so the bundle
exposes Bot, BotV0, BotV1, BotV2 and Agent exactly like bot/shell.py. Behaviour is identical (tested in
bot/tests/test_bundle.py: same actions on the same tables).

    .venv/bin/python bot/tools/bundle.py            # writes bot/dist/nolimit_bot.py and prints its size
Optional: --version N sets the default PARAMS["VERSION"] in the bundle.
"""
import argparse
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))     # bot/
DIST = os.path.join(HERE, "dist")


def read(name):
    with open(os.path.join(HERE, name + ".py")) as f:
        return f.read()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", type=int, default=None)
    ap.add_argument("--out", default=os.path.join(DIST, "nolimit_bot.py"))
    a = ap.parse_args()
    tables, brain, adapter, shell = read("bot_tables"), read("brain"), read("adapter"), read("shell")
    if a.version is not None:
        old = '"VERSION": 2,'
        if old not in brain:
            raise SystemExit("cannot find the VERSION line in brain.py")
        brain = brain.replace(old, f'"VERSION": {int(a.version)},', 1)
    digest = hashlib.sha256((tables + brain + adapter + shell).encode()).hexdigest()[:16]
    parts = [
        '"""No Limit rehearsal bot, single-file bundle (GENERATED by bot/tools/bundle.py; edit the sources in bot/).',
        "",
        f"Sources: bot/bot_tables.py, bot/brain.py, bot/adapter.py, bot/shell.py (sha256 {digest}).",
        "Agent classes: Bot (default version), BotV0, BotV1, BotV2; Agent = Bot. Standard library only.",
        '"""',
        "import sys as _bsys",
        "import types as _btypes",
        "",
        "_BUNDLE_SOURCES = {",
        f"    'bot_tables': {tables!r},",
        f"    'brain': {brain!r},",
        f"    'adapter': {adapter!r},",
        "}",
        "",
        "",
        "def _bundle_load(name, modname):",
        "    m = _bsys.modules.get(modname)",
        "    if m is not None and getattr(m, '_BUNDLE_DIGEST', None) == " + repr(digest) + ":",
        "        return m",
        "    m = _btypes.ModuleType(modname)",
        "    m.__file__ = __file__",
        "    m._BUNDLE_DIGEST = " + repr(digest),
        "    _bsys.modules[modname] = m",
        "    exec(compile(_BUNDLE_SOURCES[name], modname, 'exec'), m.__dict__)",
        "    return m",
        "",
        "",
        "_bundle_load('bot_tables', 'nolimit_bot_tables')",
        "_bundle_load('brain', 'nolimit_bot_brain')",
        "_bundle_load('adapter', 'nolimit_bot_adapter')",
        "",
        "# ======================= bot/shell.py (verbatim) =======================",
        shell,
    ]
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        f.write("\n".join(parts))
    print(f"wrote {a.out}: {os.path.getsize(a.out):,} bytes, digest {digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
