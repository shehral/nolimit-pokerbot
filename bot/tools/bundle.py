"""Bundle the bot into ONE self-contained file: bot/dist/nolimit_bot.py (for a submission that takes a single file).

How: the sources of bot_tables.py, tables_loader.py, brain.py and adapter.py are embedded as string literals and
executed into module objects registered under the same unique names the bot's own loaders look up first
(nolimit_bot_tables, nolimit_bot_tables_loader, nolimit_bot_brain, nolimit_bot_adapter). The variant layer's
light modules (variant/__init__, cards, spec, handspace, defaults, bridge: what request routing and table swapping
need; not the build engines) are embedded as the package nolimit_variant, the name tables_loader.variant_layer()
looks up first. Then shell.py's code runs in the bundle's own namespace, so the bundle exposes Bot, BotV0, BotV1,
BotV2 and Agent exactly like bot/shell.py. Behaviour is identical (tested in bot/tests/test_bundle.py: same actions
on the same tables, plain NLHE and a toss variant).

Tables: the bundle carries only the built-in NLHE tables and works on its own. A rebuilt tables module is picked up
at import from NOLIMIT_TABLES or from variant_tables.py NEXT TO THE BUNDLE FILE (tables_loader rules); without one
the bundle plays the built-in tables. --tables PATH embeds a rebuilt module instead (written next to the bundle as
variant_tables.py is the simpler event-day route; embedding is for a platform that accepts exactly one file).

    .venv/bin/python bot/tools/bundle.py            # writes bot/dist/nolimit_bot.py and prints its size
Optional: --version N sets the default PARAMS["VERSION"] in the bundle; --no-variant leaves the variant layer out
(special requests then get the adapter's safe_request answers).
"""
import argparse
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))     # bot/
ROOT = os.path.dirname(HERE)
DIST = os.path.join(HERE, "dist")
BOT_FILES = ("bot_tables", "tables_loader", "brain", "adapter", "shell")
VARIANT_FILES = ("cards", "spec", "handspace", "defaults", "bridge", "__init__")    # load order (__init__ last)


def read(name, base=HERE):
    with open(os.path.join(base, name + ".py")) as f:
        return f.read()


def sources_digest(include_variant=True):
    """Digest of every embedded source (tests compare it with the bundle header)."""
    src = "".join(read(n) for n in BOT_FILES)
    if include_variant:
        src += "".join(read(n, os.path.join(ROOT, "variant")) for n in VARIANT_FILES)
    return hashlib.sha256(src.encode()).hexdigest()[:16]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", type=int, default=None)
    ap.add_argument("--out", default=os.path.join(DIST, "nolimit_bot.py"))
    ap.add_argument("--no-variant", action="store_true")
    ap.add_argument("--tables", default=None, help="embed this rebuilt tables module (default: none, NLHE built in)")
    a = ap.parse_args(argv)
    src = {n: read(n) for n in BOT_FILES}
    if a.version is not None:
        old = '"VERSION": 2,'
        if old not in src["brain"]:
            raise SystemExit("cannot find the VERSION line in brain.py")
        src["brain"] = src["brain"].replace(old, f'"VERSION": {int(a.version)},', 1)
    vsrc = {} if a.no_variant else {n: read(n, os.path.join(ROOT, "variant")) for n in VARIANT_FILES}
    tables_src = None
    if a.tables:
        with open(a.tables) as f:
            tables_src = f.read()
    digest = sources_digest(not a.no_variant) if a.version is None and not a.tables else hashlib.sha256(
        ("".join(src.values()) + "".join(vsrc.values()) + (tables_src or "")).encode()).hexdigest()[:16]
    parts = [
        '"""No Limit rehearsal bot, single-file bundle (GENERATED by bot/tools/bundle.py; edit the sources in bot/).',
        "",
        f"Sources: bot/{{bot_tables,tables_loader,brain,adapter,shell}}.py"
        f"{'' if a.no_variant else ' + variant/{__init__,cards,spec,handspace,defaults,bridge}.py'} "
        f"(sha256 {digest}).",
        "Agent classes: Bot (default version), BotV0, BotV1, BotV2; Agent = Bot. Standard library only.",
        f"Tables: {'embedded ' + os.path.basename(a.tables) if a.tables else 'built-in NLHE; a variant_tables.py next to this file or NOLIMIT_TABLES swaps them in'}.",
        '"""',
        "import os as _bos",
        "import sys as _bsys",
        "import types as _btypes",
        "",
        "_BUNDLE_SOURCES = {",
    ]
    for n in ("bot_tables", "tables_loader", "brain", "adapter"):
        parts.append(f"    {n!r}: {src[n]!r},")
    parts.append("}")
    parts.append("_VARIANT_SOURCES = {")
    for n in VARIANT_FILES:
        if n in vsrc:
            parts.append(f"    {n!r}: {vsrc[n]!r},")
    parts.append("}")
    parts.append(f"_TABLES_SOURCE = {tables_src!r}")
    parts += [
        "",
        "",
        "def _bundle_load(name, modname, src=None, package=None):",
        "    m = _bsys.modules.get(modname)",
        "    if m is not None and getattr(m, '_BUNDLE_DIGEST', None) == " + repr(digest) + ":",
        "        return m",
        "    m = _btypes.ModuleType(modname)",
        "    m.__file__ = __file__",
        "    m._BUNDLE_DIGEST = " + repr(digest),
        "    if package is not None:",
        "        m.__package__ = package",
        "    _bsys.modules[modname] = m",
        "    try:",
        "        exec(compile(src if src is not None else _BUNDLE_SOURCES[name], modname, 'exec'), m.__dict__)",
        "    except BaseException:",
        "        del _bsys.modules[modname]",
        "        raise",
        "    return m",
        "",
        "",
        "def _bundle_variant():",
        "    if not _VARIANT_SOURCES:",
        "        return",
        "    p = _bsys.modules.get('nolimit_variant')",
        "    if p is not None and getattr(p, '_BUNDLE_DIGEST', None) == " + repr(digest) + ":",
        "        return",
        "    pkg = _btypes.ModuleType('nolimit_variant')",
        "    pkg.__file__ = __file__",
        "    pkg.__path__ = []",
        "    pkg.__package__ = 'nolimit_variant'",
        "    pkg._BUNDLE_DIGEST = " + repr(digest),
        "    _bsys.modules['nolimit_variant'] = pkg",
        "    try:",
        "        for n in " + repr(tuple(n for n in VARIANT_FILES if n != "__init__")) + ":",
        "            sub = _bundle_load(n, 'nolimit_variant.' + n, _VARIANT_SOURCES[n], 'nolimit_variant')",
        "            setattr(pkg, n, sub)",
        "        exec(compile(_VARIANT_SOURCES['__init__'], 'nolimit_variant', 'exec'), pkg.__dict__)",
        "    except BaseException:",
        "        for k in [k for k in _bsys.modules if k == 'nolimit_variant' or k.startswith('nolimit_variant.')]:",
        "            del _bsys.modules[k]",
        "",
        "",
        "try:",
        "    _bundle_variant()",
        "except BaseException:",
        "    pass",
        "if _TABLES_SOURCE is not None and not _bos.environ.get('NOLIMIT_TABLES'):",
        "    try:",
        "        import tempfile as _btmp",
        "        _bfd, _bpath = _btmp.mkstemp(prefix='nolimit_tables_', suffix='.py')",
        "        with _bos.fdopen(_bfd, 'w') as _bf:",
        "            _bf.write(_TABLES_SOURCE)",
        "        _bos.environ['NOLIMIT_TABLES'] = _bpath",
        "    except BaseException:",
        "        pass",
        "_bundle_load('bot_tables', 'nolimit_bot_tables')",
        "_bundle_load('tables_loader', 'nolimit_bot_tables_loader')",
        "_bundle_load('brain', 'nolimit_bot_brain')",
        "_bundle_load('adapter', 'nolimit_bot_adapter')",
        "",
        "# ======================= bot/shell.py (verbatim) =======================",
        src["shell"],
    ]
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        f.write("\n".join(parts))
    print(f"wrote {a.out}: {os.path.getsize(a.out):,} bytes, digest {digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
